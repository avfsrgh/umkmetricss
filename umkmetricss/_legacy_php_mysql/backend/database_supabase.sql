-- ============================================================
--  7. VIEW — ringkasan skor per submission (untuk dashboard)
--     security_invoker = true → view mengikuti RLS si pemanggil
-- ============================================================
CREATE OR REPLACE VIEW v_submission_summary
WITH (security_invoker = true) AS
SELECT
  s.id            AS submission_id,
  u.id            AS user_id,
  u.umkm_name,
  u.email,
  u.lokasi,
  u.sektor,
  s.role,
  s.status,
  s.validation_pass,
  s.submitted_at,
  s.score_ins,
  s.score_ov,
  s.score_ldi,
  s.score_weq,
  s.score_ops,
  s.score_ect,
  s.score_composite,
  s.score_on_5,
  s.health_category
FROM submissions s
JOIN users u ON u.id = s.user_id;


-- ============================================================
--  8. VIEW — rata-rata skor per faktor (untuk halaman Home)
-- ============================================================
CREATE OR REPLACE VIEW v_factor_averages
WITH (security_invoker = true) AS
SELECT
  ROUND(AVG(score_ins), 4)       AS avg_ins,
  ROUND(AVG(score_ov),  4)       AS avg_ov,
  ROUND(AVG(score_ldi), 4)       AS avg_ldi,
  ROUND(AVG(score_weq), 4)       AS avg_weq,
  ROUND(AVG(score_ops), 4)       AS avg_ops,
  ROUND(AVG(score_ect), 4)       AS avg_ect,
  ROUND(AVG(score_composite), 4) AS avg_composite,
  COUNT(*)                       AS total_submissions
FROM submissions
WHERE validation_pass = 1;


-- ============================================================
--  9. ROW LEVEL SECURITY
--     Aktif tanpa policy = anon/authenticated key tidak bisa akses.
--     Backend PHP (role postgres) mem-bypass RLS.
-- ============================================================
ALTER TABLE users                ENABLE ROW LEVEL SECURITY;
ALTER TABLE submissions          ENABLE ROW LEVEL SECURITY;
ALTER TABLE answers              ENABLE ROW LEVEL SECURITY;
ALTER TABLE validation_log       ENABLE ROW LEVEL SECURITY;
ALTER TABLE factor_definitions   ENABLE ROW LEVEL SECURITY;
ALTER TABLE question_definitions ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON v_submission_summary, v_factor_averages FROM anon, authenticated;


