SET timezone = 'Asia/Jakarta';

-- ============================================================
--  Fungsi helper: auto-update kolom updated_at
-- ============================================================
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at = (now() AT TIME ZONE 'Asia/Jakarta');
  RETURN NEW;
END $$;

-- ============================================================
--  1. TABEL USERS  (akun login owner & pegawai)
-- ============================================================
CREATE TABLE IF NOT EXISTS users (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  umkm_name     VARCHAR(150) NOT NULL,                -- Nama resmi bisnis / UMKM
  email         VARCHAR(180) NOT NULL,                -- Email bisnis (unik)
  password_hash VARCHAR(255) NOT NULL,                -- bcrypt hash
  role          TEXT         NOT NULL CHECK (role IN ('owner','employee')),
  lokasi        VARCHAR(100),                         -- Provinsi / kota
  sektor        VARCHAR(80),                          -- Bidang industri
  omzet         BIGINT CHECK (omzet IS NULL OR omzet >= 0),  -- Omzet per bulan (IDR)
  is_active     SMALLINT     NOT NULL DEFAULT 1,
  created_at    TIMESTAMP    NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Jakarta'),
  updated_at    TIMESTAMP    NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Jakarta'),
  CONSTRAINT uq_email UNIQUE (email)
);
CREATE INDEX IF NOT EXISTS idx_users_role   ON users (role);
CREATE INDEX IF NOT EXISTS idx_users_sektor ON users (sektor);
CREATE INDEX IF NOT EXISTS idx_users_umkm   ON users (LOWER(TRIM(umkm_name)));

DROP TRIGGER IF EXISTS trg_users_updated_at ON users;
CREATE TRIGGER trg_users_updated_at BEFORE UPDATE ON users
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();


-- ============================================================
--  2. TABEL SUBMISSIONS  (satu baris = satu pengiriman formulir)
-- ============================================================
CREATE TABLE IF NOT EXISTS submissions (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id         INTEGER  NOT NULL REFERENCES users(id) ON DELETE RESTRICT ON UPDATE CASCADE,
  role            TEXT     NOT NULL CHECK (role IN ('owner','employee')),
  status          TEXT     NOT NULL DEFAULT 'submitted'
                           CHECK (status IN ('draft','submitted','validated','rejected')),
  validation_pass SMALLINT NOT NULL DEFAULT 0,        -- 1 = lolos validasi backend
  submitted_at    TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Jakarta'),
  validated_at    TIMESTAMP,
  notes           TEXT,                               -- Catatan validator / admin

  -- Skor per faktor (dinormalisasi 0.0000–1.0000)
  score_ins       NUMERIC(5,4),
  score_ov        NUMERIC(5,4),
  score_ldi       NUMERIC(5,4),
  score_weq       NUMERIC(5,4),
  score_ops       NUMERIC(5,4),
  score_ect       NUMERIC(5,4),
  score_composite NUMERIC(5,4),                       -- Skor komposit tertimbang 0–1
  score_on_5      NUMERIC(4,2),                       -- Skor komposit skala 0–5
  health_category VARCHAR(30)                         -- SANGAT BAIK / BAIK / CUKUP / PERLU PERHATIAN
);
CREATE INDEX IF NOT EXISTS idx_sub_user      ON submissions (user_id);
CREATE INDEX IF NOT EXISTS idx_sub_status    ON submissions (status);
CREATE INDEX IF NOT EXISTS idx_sub_submitted ON submissions (submitted_at);


-- ============================================================
--  3. TABEL ANSWERS  (jawaban individual per pertanyaan)
-- ============================================================
CREATE TABLE IF NOT EXISTS answers (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  submission_id INTEGER     NOT NULL REFERENCES submissions(id) ON DELETE CASCADE ON UPDATE CASCADE,
  factor_key    TEXT        NOT NULL CHECK (factor_key IN ('INS','OV','LDI','WEQ','OPS','ECT')),
  question_id   VARCHAR(20) NOT NULL,                 -- ins_oh1 … weq_oh17
  question_code VARCHAR(10) NOT NULL,                 -- OH-1 … OH-35
  answer_value  SMALLINT    NOT NULL,                 -- 1–5 atau 1–3
  scale_max     SMALLINT    NOT NULL,                 -- 3 atau 5
  CONSTRAINT uq_sub_question  UNIQUE (submission_id, question_id),
  CONSTRAINT chk_answer_range CHECK (answer_value >= 1 AND answer_value <= scale_max)
);
CREATE INDEX IF NOT EXISTS idx_ans_factor ON answers (factor_key);
CREATE INDEX IF NOT EXISTS idx_ans_qid    ON answers (question_id);


-- ============================================================
--  4. TABEL VALIDATION_LOG
-- ============================================================
CREATE TABLE IF NOT EXISTS validation_log (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  submission_id INTEGER     NOT NULL REFERENCES submissions(id) ON DELETE CASCADE ON UPDATE CASCADE,
  level         TEXT        NOT NULL CHECK (level IN ('error','warning','info')),
  factor_key    VARCHAR(10),
  field_name    VARCHAR(30),
  error_code    VARCHAR(40) NOT NULL,
  message       TEXT        NOT NULL,
  created_at    TIMESTAMP   NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Jakarta')
);
CREATE INDEX IF NOT EXISTS idx_vlog_sub   ON validation_log (submission_id);
CREATE INDEX IF NOT EXISTS idx_vlog_level ON validation_log (level);


