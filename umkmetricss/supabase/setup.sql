-- ── 1. TABEL ────────────────────────────────────────────────────────────────

-- Profil pengguna (1 baris per akun Supabase Auth)
CREATE TABLE IF NOT EXISTS public.profiles (
  id         UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  umkm_name  VARCHAR(150) NOT NULL,
  email      VARCHAR(180) NOT NULL,
  role       TEXT NOT NULL CHECK (role IN ('owner','employee')),
  lokasi     VARCHAR(100),
  sektor     VARCHAR(80),
  omzet      BIGINT CHECK (omzet IS NULL OR omzet >= 0),
  is_active  BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_profiles_role  ON public.profiles (role);
CREATE INDEX IF NOT EXISTS idx_profiles_umkm  ON public.profiles (lower(trim(umkm_name)));
-- Satu UMKM hanya boleh punya satu Owner
CREATE UNIQUE INDEX IF NOT EXISTS uq_profiles_owner_per_umkm
  ON public.profiles (lower(trim(umkm_name))) WHERE role = 'owner';

CREATE TABLE IF NOT EXISTS public.submissions (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id         UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  role            TEXT NOT NULL CHECK (role IN ('owner','employee')),
  status          TEXT NOT NULL DEFAULT 'submitted'
                  CHECK (status IN ('draft','submitted','validated','rejected')),
  validation_pass SMALLINT NOT NULL DEFAULT 0,
  submitted_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  validated_at    TIMESTAMPTZ,
  notes           TEXT,
  score_ins       NUMERIC(5,4),
  score_ov        NUMERIC(5,4),
  score_ldi       NUMERIC(5,4),
  score_weq       NUMERIC(5,4),
  score_ops       NUMERIC(5,4),
  score_ect       NUMERIC(5,4),
  score_composite NUMERIC(5,4),
  score_on_5      NUMERIC(4,2),
  health_category VARCHAR(30)
);
CREATE INDEX IF NOT EXISTS idx_sub_user      ON public.submissions (user_id);
CREATE INDEX IF NOT EXISTS idx_sub_submitted ON public.submissions (submitted_at);
-- Satu akun hanya boleh mengisi kuesioner sekali
CREATE UNIQUE INDEX IF NOT EXISTS uq_sub_one_per_user ON public.submissions (user_id);

CREATE TABLE IF NOT EXISTS public.answers (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  submission_id BIGINT NOT NULL REFERENCES public.submissions(id) ON DELETE CASCADE,
  factor_key    TEXT NOT NULL CHECK (factor_key IN ('INS','OV','LDI','WEQ','OPS','ECT')),
  question_id   VARCHAR(20) NOT NULL,
  question_code VARCHAR(10) NOT NULL,
  answer_value  SMALLINT NOT NULL,
  scale_max     SMALLINT NOT NULL,
  CONSTRAINT uq_sub_question  UNIQUE (submission_id, question_id),
  CONSTRAINT chk_answer_range CHECK (answer_value >= 1 AND answer_value <= scale_max)
);

CREATE TABLE IF NOT EXISTS public.validation_log (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  submission_id BIGINT NOT NULL REFERENCES public.submissions(id) ON DELETE CASCADE,
  level         TEXT NOT NULL CHECK (level IN ('error','warning','info')),
  factor_key    VARCHAR(10),
  field_name    VARCHAR(30),
  error_code    VARCHAR(40) NOT NULL,
  message       TEXT NOT NULL,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.factor_definitions (
  key         VARCHAR(5) PRIMARY KEY,
  label       VARCHAR(80) NOT NULL,
  role        TEXT NOT NULL CHECK (role IN ('owner','employee')),
  weight      NUMERIC(4,2) NOT NULL,
  scale_max   SMALLINT NOT NULL,
  description VARCHAR(200)
);

CREATE TABLE IF NOT EXISTS public.question_definitions (
  id          SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  question_id VARCHAR(20) NOT NULL,
  code        VARCHAR(10) NOT NULL,
  factor_key  VARCHAR(5)  NOT NULL,
  text_id     TEXT NOT NULL,
  text_en     TEXT NOT NULL,
  scale_max   SMALLINT NOT NULL,
  is_required SMALLINT NOT NULL DEFAULT 1,
  sort_order  SMALLINT NOT NULL DEFAULT 0,
  CONSTRAINT uq_qid  UNIQUE (question_id),
  CONSTRAINT uq_code UNIQUE (code)
);

