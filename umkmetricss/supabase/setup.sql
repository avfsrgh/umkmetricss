-- ── 4. TRIGGER: buat profil otomatis saat user mendaftar (Supabase Auth) ───
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  m JSONB := COALESCE(NEW.raw_user_meta_data, '{}'::jsonb);
  v_role TEXT := COALESCE(m->>'role', 'owner');
  v_name TEXT := trim(COALESCE(m->>'umkm_name', ''));
BEGIN
  IF v_role NOT IN ('owner','employee') THEN
    RAISE EXCEPTION 'Peran tidak valid.';
  END IF;
  IF char_length(v_name) < 2 THEN
    RAISE EXCEPTION 'Nama UMKM minimal 2 karakter.';
  END IF;

  INSERT INTO public.profiles (id, umkm_name, email, role, lokasi, sektor, omzet)
  VALUES (
    NEW.id, v_name, lower(NEW.email), v_role,
    NULLIF(trim(COALESCE(m->>'lokasi','')), ''),
    NULLIF(trim(COALESCE(m->>'sektor','')), ''),
    CASE WHEN COALESCE(m->>'omzet','') ~ '^[0-9]+$' THEN (m->>'omzet')::bigint END
  );
  RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

-- ── 5. RPC: cek pendaftaran Owner ganda (boleh dipanggil sebelum login) ────
CREATE OR REPLACE FUNCTION public.check_registration(p_umkm_name TEXT, p_role TEXT)
RETURNS JSONB LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF p_role = 'owner' AND EXISTS (
       SELECT 1 FROM public.profiles
       WHERE role = 'owner' AND lower(trim(umkm_name)) = lower(trim(p_umkm_name))) THEN
    RETURN jsonb_build_object('ok', false, 'message',
      'UMKM "' || p_umkm_name || '" sudah memiliki Owner terdaftar. Pendaftaran Owner baru untuk UMKM yang sama tidak diperbolehkan.');
  END IF;
  RETURN jsonb_build_object('ok', true);
END $$;

-- ── 6. RPC: kirim kuesioner (validasi + skor + simpan) ─────────────────────
--  Port dari validator.php + endpoint submit di api.php.
--  Mengembalikan JSON: { ok, message, data }
CREATE OR REPLACE FUNCTION public.submit_questionnaire(p_answers JSONB)
RETURNS JSONB LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_uid      UUID := auth.uid();
  v_prof     public.profiles%ROWTYPE;
  v_factors  TEXT[];
  f          RECORD;
  q          RECORD;
  v_errors   JSONB := '[]'::jsonb;
  v_warnings JSONB := '[]'::jsonb;
  v_scores   JSONB := '{}'::jsonb;     -- per faktor (format respons)
  v_norm     JSONB := '{}'::jsonb;     -- key -> normScore (hanya yg tidak null)
  v_clean    JSONB := '{}'::jsonb;     -- question_id -> nilai valid
  v_raw      TEXT;
  v_int      INT;
  v_vals     INT[];
  v_answered INT;
  v_total    INT;
  v_pct      NUMERIC;
  v_mean     NUMERIC;
  v_normf    NUMERIC;
  v_ws NUMERIC := 0; v_wt NUMERIC := 0;
  v_comp NUMERIC; v_s5 NUMERIC; v_cat TEXT;
  v_composite JSONB := NULL;
  v_valid    BOOLEAN;
  v_sub_id   BIGINT;
  v_owner    public.submissions%ROWTYPE;
  v_avg_ov NUMERIC; v_avg_ldi NUMERIC; v_avg_weq NUMERIC;
  v_n_ins NUMERIC; v_n_ops NUMERIC; v_n_ect NUMERIC;
  v_n_ov NUMERIC;  v_n_ldi NUMERIC; v_n_weq NUMERIC;
  v_max NUMERIC; v_min NUMERIC; v_hk TEXT; v_lk TEXT;
  k TEXT; val NUMERIC; lg JSONB; kv RECORD;
BEGIN
  IF v_uid IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'status', 401, 'message', 'Tidak terautentikasi. Silakan login.');
  END IF;

  SELECT * INTO v_prof FROM public.profiles WHERE id = v_uid;
  IF NOT FOUND THEN
    RETURN jsonb_build_object('ok', false, 'status', 401, 'message', 'Profil tidak ditemukan.');
  END IF;

  IF EXISTS (SELECT 1 FROM public.submissions WHERE user_id = v_uid) THEN
    RETURN jsonb_build_object('ok', false, 'status', 403, 'message', 'Anda hanya dapat mengisi kuesioner sekali.');
  END IF;

  v_factors := CASE v_prof.role WHEN 'owner' THEN ARRAY['INS','ECT','OPS']
                                ELSE ARRAY['OV','LDI','WEQ'] END;

  -- ── Validasi per faktor ──
  FOR f IN SELECT * FROM public.factor_definitions
           WHERE key::text = ANY(v_factors) ORDER BY array_position(v_factors, key::text) LOOP
    v_vals := ARRAY[]::INT[]; v_answered := 0; v_total := 0;

    FOR q IN SELECT * FROM public.question_definitions
             WHERE factor_key = f.key ORDER BY sort_order LOOP
      v_total := v_total + 1;
      v_raw := p_answers ->> q.question_id;

      IF v_raw IS NULL OR v_raw = '' THEN
        v_errors := v_errors || jsonb_build_object('field', q.question_id, 'factor', f.key, 'code', 'MISSING',
          'message', q.code || ': "' || q.text_id || '" wajib dijawab.');
        CONTINUE;
      END IF;

      IF v_raw !~ '^[0-9]+(\.[0-9]+)?$' THEN
        v_int := NULL;
      ELSE
        v_int := trunc(v_raw::numeric)::int;
      END IF;

      IF v_int IS NULL OR v_int < 1 OR v_int > f.scale_max THEN
        v_errors := v_errors || jsonb_build_object('field', q.question_id, 'factor', f.key, 'code', 'OUT_OF_RANGE',
          'message', q.code || ': Nilai ' || v_raw || ' di luar rentang (1–' || f.scale_max || ').');
        CONTINUE;
      END IF;

      v_vals := v_vals || v_int;
      v_answered := v_answered + 1;
      v_clean := v_clean || jsonb_build_object(q.question_id, v_int);
    END LOOP;

    v_pct := CASE WHEN v_total > 0 THEN round(v_answered::numeric / v_total, 4) ELSE 0 END;

    IF v_answered > 0 AND v_pct < 0.8 THEN
      v_warnings := v_warnings || jsonb_build_object('field', f.key, 'factor', f.key, 'code', 'LOW_COMPLETION',
        'message', 'Faktor ' || f.key || ': ' || v_answered || '/' || v_total || ' dijawab.');
    END IF;
    IF v_answered >= 4 AND (SELECT count(DISTINCT x) FROM unnest(v_vals) x) = 1 THEN
      v_warnings := v_warnings || jsonb_build_object('field', f.key, 'factor', f.key, 'code', 'STRAIGHT_LINE',
        'message', 'Faktor ' || f.key || ': semua jawaban identik (' || v_vals[1] || ').');
    END IF;

    IF v_answered > 0 THEN
      v_mean  := round((SELECT sum(x) FROM unnest(v_vals) x)::numeric / v_answered, 4);
      v_normf := round(v_mean / f.scale_max, 4);
      v_norm  := v_norm || jsonb_build_object(f.key, v_normf);
      v_ws := v_ws + v_normf * f.weight;
      v_wt := v_wt + f.weight;
    ELSE
      v_mean := NULL; v_normf := NULL;
    END IF;

    v_scores := v_scores || jsonb_build_object(f.key, jsonb_build_object(
      'rawMean', v_mean, 'normScore', v_normf,
      'scoreOn5', CASE WHEN v_normf IS NOT NULL THEN round(v_normf * 5, 2) END,
      'completionPct', v_pct, 'answered', v_answered, 'total', v_total));
  END LOOP;

  -- ── Kesenjangan antar faktor ──
  IF (SELECT count(*) FROM jsonb_object_keys(v_norm)) >= 2 THEN
    v_max := NULL; v_min := NULL;
    FOR kv IN SELECT key, value::numeric AS v FROM jsonb_each_text(v_norm) LOOP
      IF v_max IS NULL OR kv.v > v_max THEN v_max := kv.v; v_hk := kv.key; END IF;
      IF v_min IS NULL OR kv.v < v_min THEN v_min := kv.v; v_lk := kv.key; END IF;
    END LOOP;
    IF round(v_max - v_min, 4) > 0.5 THEN
      v_warnings := v_warnings || jsonb_build_object('field', NULL, 'factor', '', 'code', 'DISPARITY',
        'message', 'Kesenjangan besar antara ' || v_hk || ' (' || round(v_max*100) || '%) dan ' || v_lk || ' (' || round(v_min*100) || '%).');
    END IF;
  END IF;

  -- ── Skor komposit ──
  IF v_wt > 0 THEN
    v_comp := round(v_ws / v_wt, 4);
    v_s5   := round(v_comp * 5, 2);
    v_cat  := CASE WHEN v_comp >= 0.80 THEN 'SANGAT BAIK' WHEN v_comp >= 0.60 THEN 'BAIK'
                   WHEN v_comp >= 0.40 THEN 'CUKUP' ELSE 'PERLU PERHATIAN' END;
    v_composite := jsonb_build_object('composite', v_comp, 'scoreOn5', v_s5, 'category', v_cat);
  END IF;

  v_valid := (jsonb_array_length(v_errors) = 0);

  -- Pegawai dengan jawaban tidak valid ditolak tanpa menyimpan apa pun
  IF v_prof.role = 'employee' AND NOT v_valid THEN
    RETURN jsonb_build_object('ok', false, 'status', 422,
      'message', 'Formulir ditolak: ' || jsonb_array_length(v_errors) || ' error ditemukan.',
      'data', jsonb_build_object('errors', v_errors, 'warnings', v_warnings));
  END IF;

  -- ════════════════ OWNER ════════════════
  IF v_prof.role = 'owner' THEN
    INSERT INTO public.submissions
      (user_id, role, status, validation_pass,
       score_ins, score_ov, score_ldi, score_weq, score_ops, score_ect,
       score_composite, score_on_5, health_category)
    VALUES
      (v_uid, 'owner', CASE WHEN v_valid THEN 'submitted' ELSE 'rejected' END, CASE WHEN v_valid THEN 1 ELSE 0 END,
       (v_norm->>'INS')::numeric, NULL, NULL, NULL, (v_norm->>'OPS')::numeric, (v_norm->>'ECT')::numeric,
       v_comp, v_s5, v_cat)
    RETURNING id INTO v_sub_id;

    INSERT INTO public.answers (submission_id, factor_key, question_id, question_code, answer_value, scale_max)
    SELECT v_sub_id, qd.factor_key, qd.question_id, qd.code, (c.value)::int, qd.scale_max
    FROM jsonb_each_text(v_clean) c
    JOIN public.question_definitions qd ON qd.question_id = c.key;

    FOR lg IN SELECT jsonb_set(e, '{level}', '"error"') FROM jsonb_array_elements(v_errors) e
              UNION ALL
              SELECT jsonb_set(w, '{level}', '"warning"') FROM jsonb_array_elements(v_warnings) w LOOP
      INSERT INTO public.validation_log (submission_id, level, factor_key, field_name, error_code, message)
      VALUES (v_sub_id, lg->>'level', NULLIF(lg->>'factor',''), lg->>'field', lg->>'code', lg->>'message');
    END LOOP;

    IF NOT v_valid THEN
      RETURN jsonb_build_object('ok', false, 'status', 422,
        'message', 'Formulir ditolak: ' || jsonb_array_length(v_errors) || ' error ditemukan.',
        'data', jsonb_build_object('errors', v_errors, 'warnings', v_warnings, 'submission_id', v_sub_id));
    END IF;

    RETURN jsonb_build_object('ok', true, 'message', 'Formulir berhasil disimpan.',
      'data', jsonb_build_object('submission_id', v_sub_id, 'scores', v_scores,
                                 'composite', v_composite, 'warnings', v_warnings));
  END IF;

  -- ════════════════ PEGAWAI ════════════════
  SELECT s.* INTO v_owner
  FROM public.submissions s JOIN public.profiles p ON p.id = s.user_id
  WHERE s.role = 'owner' AND s.validation_pass = 1
    AND lower(trim(p.umkm_name)) = lower(trim(v_prof.umkm_name))
  ORDER BY s.submitted_at DESC LIMIT 1;

  IF NOT FOUND THEN
    RETURN jsonb_build_object('ok', false, 'status', 403, 'message',
      'Owner dari UMKM "' || v_prof.umkm_name || '" belum mengisi kuesioner. Pegawai hanya dapat mengisi kuesioner setelah Owner mengisinya.');
  END IF;

  -- 1. catat submission pegawai (tidak ikut statistik: validation_pass = 0)
  INSERT INTO public.submissions
    (user_id, role, status, validation_pass, score_ov, score_ldi, score_weq,
     score_composite, score_on_5, health_category)
  VALUES
    (v_uid, 'employee', 'submitted', 0,
     (v_norm->>'OV')::numeric, (v_norm->>'LDI')::numeric, (v_norm->>'WEQ')::numeric,
     v_comp, v_s5, v_cat);

  -- 2. rata-rata semua pegawai UMKM yang sama (termasuk yang baru)
  SELECT avg(s.score_ov), avg(s.score_ldi), avg(s.score_weq)
    INTO v_avg_ov, v_avg_ldi, v_avg_weq
  FROM public.submissions s JOIN public.profiles p ON p.id = s.user_id
  WHERE s.role = 'employee' AND lower(trim(p.umkm_name)) = lower(trim(v_prof.umkm_name));

  v_n_ins := v_owner.score_ins; v_n_ops := v_owner.score_ops; v_n_ect := v_owner.score_ect;
  v_n_ov  := round(v_avg_ov, 4); v_n_ldi := round(v_avg_ldi, 4); v_n_weq := round(v_avg_weq, 4);

  -- 3. komposit gabungan owner + rata-rata pegawai
  v_ws := 0; v_wt := 0;
  FOR kv IN
    SELECT fd.key, fd.weight,
           CASE fd.key WHEN 'INS' THEN v_n_ins WHEN 'OPS' THEN v_n_ops WHEN 'ECT' THEN v_n_ect
                       WHEN 'OV' THEN v_n_ov WHEN 'LDI' THEN v_n_ldi WHEN 'WEQ' THEN v_n_weq END AS n
    FROM public.factor_definitions fd LOOP
    IF kv.n IS NOT NULL THEN v_ws := v_ws + kv.n * kv.weight; v_wt := v_wt + kv.weight; END IF;
  END LOOP;
  v_comp := round(v_ws / v_wt, 4);
  v_s5   := round(v_comp * 5, 2);
  v_cat  := CASE WHEN v_comp >= 0.80 THEN 'SANGAT BAIK' WHEN v_comp >= 0.60 THEN 'BAIK'
                 WHEN v_comp >= 0.40 THEN 'CUKUP' ELSE 'PERLU PERHATIAN' END;
  v_composite := jsonb_build_object('composite', v_comp, 'scoreOn5', v_s5, 'category', v_cat);

  -- 4. perbarui submission Owner dengan hasil gabungan
  UPDATE public.submissions
  SET score_ov = v_n_ov, score_ldi = v_n_ldi, score_weq = v_n_weq,
      score_composite = v_comp, score_on_5 = v_s5, health_category = v_cat,
      status = 'validated', validation_pass = 1, validated_at = now()
  WHERE id = v_owner.id;
  v_sub_id := v_owner.id;

  -- 5. simpan/perbarui jawaban pegawai pada submission Owner
  INSERT INTO public.answers (submission_id, factor_key, question_id, question_code, answer_value, scale_max)
  SELECT v_sub_id, qd.factor_key, qd.question_id, qd.code, (c.value)::int, qd.scale_max
  FROM jsonb_each_text(v_clean) c
  JOIN public.question_definitions qd ON qd.question_id = c.key
  ON CONFLICT (submission_id, question_id) DO UPDATE SET answer_value = EXCLUDED.answer_value;

  FOR lg IN SELECT jsonb_set(e, '{level}', '"error"') FROM jsonb_array_elements(v_errors) e
            UNION ALL
            SELECT jsonb_set(w, '{level}', '"warning"') FROM jsonb_array_elements(v_warnings) w LOOP
    INSERT INTO public.validation_log (submission_id, level, factor_key, field_name, error_code, message)
    VALUES (v_sub_id, lg->>'level', NULLIF(lg->>'factor',''), lg->>'field', lg->>'code', lg->>'message');
  END LOOP;

  -- 6. respons: skor gabungan
  v_scores := '{}'::jsonb;
  FOR kv IN SELECT * FROM (VALUES ('INS', v_n_ins), ('OPS', v_n_ops), ('ECT', v_n_ect),
                                  ('OV', v_n_ov), ('LDI', v_n_ldi), ('WEQ', v_n_weq)) AS t(key, n) LOOP
    v_scores := v_scores || jsonb_build_object(kv.key, jsonb_build_object(
      'normScore', kv.n, 'scoreOn5', CASE WHEN kv.n IS NOT NULL THEN round(kv.n * 5, 2) END));
  END LOOP;

  RETURN jsonb_build_object('ok', true, 'message', 'Formulir berhasil disimpan.',
    'data', jsonb_build_object('submission_id', v_sub_id, 'scores', v_scores,
                               'composite', v_composite, 'warnings', v_warnings));
END $$;

-- ── 7. RPC: data dashboard (agregat semua UMKM, hanya untuk user login) ────
CREATE OR REPLACE FUNCTION public.factor_averages()
RETURNS JSONB LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
DECLARE r JSONB;
BEGIN
  IF auth.uid() IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'status', 401, 'message', 'Tidak terautentikasi. Silakan login.');
  END IF;
  SELECT jsonb_build_object(
    'avg_ins', round(avg(score_ins),4), 'avg_ov', round(avg(score_ov),4), 'avg_ldi', round(avg(score_ldi),4),
    'avg_weq', round(avg(score_weq),4), 'avg_ops', round(avg(score_ops),4), 'avg_ect', round(avg(score_ect),4),
    'avg_composite', round(avg(score_composite),4), 'total_submissions', count(*),
    'avg_ins_5', round(COALESCE(avg(score_ins),0)*5,2), 'avg_ov_5',  round(COALESCE(avg(score_ov),0)*5,2),
    'avg_ldi_5', round(COALESCE(avg(score_ldi),0)*5,2), 'avg_weq_5', round(COALESCE(avg(score_weq),0)*5,2),
    'avg_ops_5', round(COALESCE(avg(score_ops),0)*5,2), 'avg_ect_5', round(COALESCE(avg(score_ect),0)*5,2))
  INTO r FROM public.submissions WHERE validation_pass = 1;
  RETURN jsonb_build_object('ok', true, 'data', r);
END $$;

CREATE OR REPLACE FUNCTION public.dashboard_stats()
RETURNS JSONB LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
DECLARE st JSONB; fa JSONB;
BEGIN
  IF auth.uid() IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'status', 401, 'message', 'Tidak terautentikasi. Silakan login.');
  END IF;
  SELECT jsonb_build_object(
    'total_umkm', count(*),
    'total_valid', count(*) FILTER (WHERE validation_pass = 1),
    'avg_score_pct', round(avg(score_composite)*100, 1),
    'best_score', round(max(score_composite)*5, 2),
    'worst_score', round(min(score_composite)*5, 2),
    'sehat_count', count(*) FILTER (WHERE score_composite >= 0.6))
  INTO st FROM public.submissions WHERE validation_pass = 1;
  fa := public.factor_averages() -> 'data';
  RETURN jsonb_build_object('ok', true, 'data', jsonb_build_object('stats', st, 'factor_averages', fa));
END $$;

CREATE OR REPLACE FUNCTION public.umkm_list(p_limit INT DEFAULT 15, p_offset INT DEFAULT 0, p_search TEXT DEFAULT '')
RETURNS JSONB LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_limit INT := LEAST(GREATEST(COALESCE(p_limit, 15), 1), 1000);
  v_offset INT := GREATEST(COALESCE(p_offset, 0), 0);
  v_pat TEXT := '%' || COALESCE(p_search, '') || '%';
  v_rows JSONB; v_total BIGINT;
BEGIN
  IF auth.uid() IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'status', 401, 'message', 'Tidak terautentikasi. Silakan login.');
  END IF;

  SELECT count(*) INTO v_total
  FROM public.submissions s JOIN public.profiles u ON u.id = s.user_id
  WHERE s.validation_pass = 1
    AND (u.umkm_name ILIKE v_pat OR u.lokasi ILIKE v_pat OR u.sektor ILIKE v_pat);

  SELECT COALESCE(jsonb_agg(to_jsonb(t) ORDER BY t.submitted_at), '[]'::jsonb) INTO v_rows FROM (
    SELECT s.id AS submission_id, u.umkm_name, u.lokasi, u.sektor, s.role,
           s.score_composite, s.score_on_5, s.health_category, s.submitted_at, u.omzet,
           round(s.score_ins*5,2) AS score_ins_5, round(s.score_ov*5,2)  AS score_ov_5,
           round(s.score_ldi*5,2) AS score_ldi_5, round(s.score_weq*5,2) AS score_weq_5,
           round(s.score_ops*5,2) AS score_ops_5, round(s.score_ect*5,2) AS score_ect_5
    FROM public.submissions s JOIN public.profiles u ON u.id = s.user_id
    WHERE s.validation_pass = 1
      AND (u.umkm_name ILIKE v_pat OR u.lokasi ILIKE v_pat OR u.sektor ILIKE v_pat)
    ORDER BY s.submitted_at ASC
    LIMIT v_limit OFFSET v_offset) t;

  RETURN jsonb_build_object('ok', true, 'data',
    jsonb_build_object('rows', v_rows, 'total', v_total, 'limit', v_limit, 'offset', v_offset));
END $$;

